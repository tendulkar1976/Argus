"""Pydantic schemas for the Argus Gateway API (Phase 4.2).

Defines public request and response contracts for upstream frontier model dispatch,
with strict separation between actual upstream usage, verified costs, and heuristic optimization savings.
"""

from typing import Any, Dict, Optional
from pydantic import BaseModel, Field, field_validator

from app.schemas.optimizer import OptimizationMode


class GatewayDispatchRequest(BaseModel):
    """Client request to dispatch a prompt through Argus to the upstream frontier model.

    All incoming client requests are unconditionally processed through the local prompt
    optimization and semantic candidate validation pipeline. Extra/bypass fields are forbidden.
    """

    model_config = {
        "extra": "forbid",
    }

    prompt: str = Field(
        ...,
        min_length=1,
        description="The prompt text to process and dispatch",
    )
    mode: OptimizationMode = Field(
        default="balanced",
        description="Argus prompt optimization profile ('balanced', 'concise', or 'structure')",
    )
    system_prompt: Optional[str] = Field(
        default=None,
        description="Optional system instruction passed to the frontier model",
    )
    target_model: Optional[str] = Field(
        default=None,
        description="Optional target model identifier override (defaults to backend configured model)",
    )

    @field_validator("prompt")
    @classmethod
    def validate_prompt_not_whitespace(cls, v: str) -> str:
        trimmed = v.strip()
        if not trimmed:
            raise ValueError("Prompt cannot be empty or contain only whitespace.")
        return trimmed



class GatewayUsageTelemetry(BaseModel):
    """Actual token usage and financial cost derived exclusively from upstream API metrics."""

    actual_input_tokens: Optional[int] = Field(
        default=None,
        description="Actual prompt input tokens reported by upstream provider",
    )
    actual_output_tokens: Optional[int] = Field(
        default=None,
        description="Actual completion tokens reported by upstream provider",
    )
    actual_total_tokens: Optional[int] = Field(
        default=None,
        description="Total tokens billed by upstream provider",
    )
    cached_tokens: Optional[int] = Field(
        default=None,
        description="Portion of input tokens served from provider prompt cache",
    )
    reasoning_tokens: Optional[int] = Field(
        default=None,
        description="Reasoning tokens consumed (accounted within actual_output_tokens, not double-counted)",
    )
    actual_cost_usd: Optional[float] = Field(
        default=None,
        description="Verified cost calculated from actual token usage and verified pricing table",
    )
    actual_input_cost_usd: Optional[float] = Field(
        default=None,
        description="Calculated cost for input tokens (including cached token rates)",
    )
    actual_output_cost_usd: Optional[float] = Field(
        default=None,
        description="Calculated cost for generated output tokens",
    )
    pricing_status: str = Field(
        description="Status of cost calculation: 'calculated', 'pricing_unavailable', 'usage_unavailable', or 'unsupported_context_bounds'",
    )
    currency: str = Field(default="USD", description="Currency unit for costs")
    pricing_tier: Optional[str] = Field(default=None, description="Applied pricing tier")
    pricing_source_url: Optional[str] = Field(default=None, description="Official documentation source for rates")
    last_verified_date: Optional[str] = Field(default=None, description="Date rates were verified against documentation")


class GatewaySavingsTelemetry(BaseModel):
    """Heuristic optimization savings estimates clearly separated from verified upstream usage."""

    baseline_estimated_tokens: int = Field(
        description="Estimated token count of the unoptimized input prompt (~4 chars/token heuristic)"
    )
    optimized_estimated_tokens: int = Field(
        description="Estimated token count of the prompt sent to the upstream model"
    )
    estimated_token_savings: int = Field(
        description="Projected reduction in input tokens achieved by Argus optimization"
    )
    estimated_cost_savings_usd: Optional[float] = Field(
        default=None,
        description="Projected input token dollar savings based on verified standard input rate",
    )
    savings_disclaimer: str = Field(
        description="Mandatory disclosure explaining that savings are heuristic estimates"
    )


class GatewayDispatchResponse(BaseModel):
    """Public response containing the model's generated answer and honest telemetry."""

    model_response: str = Field(description="The response content generated by the upstream frontier model")
    effective_prompt: str = Field(description="The exact prompt text dispatched to the upstream model")
    was_optimized: bool = Field(description="Whether local prompt optimization was applied to the prompt")
    provider: str = Field(description="The upstream LLM provider (e.g. 'openai')")
    model: str = Field(description="The upstream model ID utilized for generation")
    execution_latency_ms: int = Field(description="Duration of upstream model execution in milliseconds")
    optimization_latency_ms: int = Field(
        default=0,
        description="Duration of local prompt optimization in milliseconds (0 if bypassed)",
    )
    usage: GatewayUsageTelemetry = Field(description="Actual upstream token consumption and verified cost")
    estimated_savings: GatewaySavingsTelemetry = Field(
        description="Heuristic savings projections comparing baseline vs. optimized prompt"
    )
    optimization_summary: Optional[Dict[str, Any]] = Field(
        default=None,
        description="Metadata from local optimization stage (strategy, constraints preserved, outcome)",
    )
